const MARKET_LIST = Object.values(MARKET_PAGES);

function marketPath(marketOrName) {
  const market = typeof marketOrName === 'object' && marketOrName
    ? marketOrName
    : marketForName(marketOrName);
  return market ? `/short-term-rentals/${market.slug}` : null;
}

function marketForName(value) {
  const normalized = String(value || '').trim().toLowerCase();
  return MARKET_LIST.find(market => market.matchNames.includes(normalized)) || null;
}

function marketMatchesListing(market, listing) {
  const values = [listing.location, listing.city]
    .filter(Boolean)
    .map(value => String(value).trim().toLowerCase());
  return values.some(value => market.matchNames.includes(value));
}

function marketUrl(value) {
  const market = marketForName(value);
  return market ? marketPath(market) : `/properties?location=${encodeURIComponent(value)}`;
}

module.exports = {
  MARKET_PAGES,
  MARKET_LIST,
  marketPath,
  marketForName,
  marketMatchesListing,
  marketUrl
};
