// Listing-image proxy.
//
// Public pages used to embed Supabase Storage URLs directly, so every visitor
// and crawler hit downloaded bytes from Supabase and counted against the
// project's egress quota (which bots exhausted). Instead, pages now reference
// /img/<object> on our own domain; this route fetches the object from the
// public bucket once and replies with long-lived cache headers, so Vercel's
// edge CDN absorbs all repeat traffic and Supabase only sees cache misses.
//
// Cache-forever is safe because uploaded filenames are unique and object
// contents never change after upload (see storeImage in utils/storage.js).

const SUPABASE_URL = process.env.SUPABASE_URL;
const BUCKET = process.env.SUPABASE_STORAGE_BUCKET || 'listings';

// Object names are generated by us (timestamp-random[.opt].ext) — anything
// outside this alphabet is not ours to serve.
const NAME_RE = /^[A-Za-z0-9_-]{1,200}(\.[A-Za-z0-9]{1,10}){0,2}$/;

// Rewrite a stored public-bucket URL to its proxied path. Anything else
// (Google Drive links, local /uploads paths, already-proxied paths) passes
// through untouched, so old rows keep working and the rewrite is idempotent.
function toProxyUrl(url) {
  if (typeof url !== 'string') return url;
  const m = url.match(/^https:\/\/[a-z0-9-]+\.supabase\.co\/storage\/v1\/object\/public\/([^/?#]+)\/([^/?#]+)$/);
  if (!m || m[1] !== BUCKET || !NAME_RE.test(m[2])) return url;
  return '/img/' + m[2];
}

// Rewrite every image field on a listing row, in place. Use only on rows
// headed for public rendering — admin screens keep canonical URLs so edits
// save the original Supabase URL back to the database.
function rewriteListingImages(listing) {
  if (!listing) return listing;
  if (Array.isArray(listing.images)) listing.images = listing.images.map(toProxyUrl);
  if (listing.floor_plan_image) listing.floor_plan_image = toProxyUrl(listing.floor_plan_image);
  return listing;
}

// GET /img/:name — fetch from the public bucket and serve with immutable
// cache headers. s-maxage makes Vercel's CDN cache the response; max-age
// makes browsers cache it too.
async function proxyImage(req, res) {
  const name = req.params.name;
  if (!SUPABASE_URL || !NAME_RE.test(name)) {
    return res.status(404).type('text/plain').send('Not found');
  }
  try {
    const upstream = await fetch(
      `${SUPABASE_URL}/storage/v1/object/public/${BUCKET}/${encodeURIComponent(name)}`
    );
    if (!upstream.ok) {
      // Never cache failures (404, or 402 while the project is over quota),
      // so they clear as soon as the bucket is reachable again.
      res.set('Cache-Control', 'no-store');
      return res.status(upstream.status === 404 ? 404 : 502).type('text/plain').send('Image unavailable');
    }
    res.status(200);
    res.set('Content-Type', upstream.headers.get('content-type') || 'application/octet-stream');
    res.set('Cache-Control', 'public, max-age=31536000, s-maxage=31536000, immutable');
    const buffer = Buffer.from(await upstream.arrayBuffer());
    res.set('Content-Length', String(buffer.length));
    res.end(buffer);
  } catch (err) {
    console.error('[imageProxy] fetch failed:', err.message);
    res.set('Cache-Control', 'no-store');
    res.status(502).type('text/plain').send('Image unavailable');
  }
}

module.exports = { toProxyUrl, rewriteListingImages, proxyImage };
